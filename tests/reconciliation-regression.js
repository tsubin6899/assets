const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const store = new Map();
const context = {window: {dispatchEvent() {}}, localStorage: {getItem: key => store.get(key) || null, setItem: (key, value) => store.set(key, value)}, CustomEvent: class {}, console};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../finance-core.js'), 'utf8'), context);
const core = context.window.FinanceCore;
core.addAccount({name: 'Card', type: '信用卡', currency: 'TWD', openingBalance: 47146});
core.addAccount({name: 'Bank', type: '銀行帳戶', currency: 'TWD', openingBalance: 10000});
const balance = name => {const {ledger, assets} = core.load();return core.accountBalances(ledger, assets).find(row => row.name === name).balance;};
const reconcile = amount => core.addReconciliation({account: 'Card', date: core.localDate(), actualBalance: amount});
reconcile(15615);
assert.equal(balance('Card'), 15615);
assert.equal(balance('Bank'), 10000);
let data = core.load();
const adjustment = data.ledger.entries.find(row => row.isReconciliationAdjustment);
assert.equal(adjustment.type, 'income');
assert.equal(adjustment.amount, 31531);
assert.equal(core.insights().month.expense, 0, 'a reconciliation adjustment must not count as monthly spending');
reconcile(15615);
assert.equal(balance('Card'), 15615);
assert.equal(core.load().ledger.entries.length, data.ledger.entries.length);
core.removeReconciliation(core.load().ledger.reconciliations.at(-1).id);
core.removeReconciliation(data.ledger.reconciliations[0].id);
assert.equal(balance('Card'), 47146);
reconcile(50000);
assert.equal(balance('Card'), 50000);
core.addReconciliation({account: 'Bank', actualBalance: 9000, date: core.localDate()});
assert.equal(balance('Bank'), 9000);
const removedAdjustment = core.load().ledger.entries.find(row => row.isReconciliationAdjustment);
core.removeReconciliation(core.load().ledger.reconciliations.find(row => row.entryId === removedAdjustment.id).id);
assert.equal(core.load().ledger.entries.some(row => row.id === removedAdjustment.id), false, 'removing a reconciliation must remove its adjustment entry');
assert.equal(core.load().ledger.recycleBin.some(row => row.kind === 'entry' && row.row.id === removedAdjustment.id), true, 'removed adjustment must be tombstoned so sync cannot restore it');
console.log('reconciliation regression OK');
